import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../lab/index.html',import.meta.url),'utf8');
const source=html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(source);
const from=source.indexOf('function spotAt('),to=source.indexOf('function loadProject(){');
const funcs=source.slice(from,to);
const ctx=vm.createContext({});
vm.runInContext(`function sameEnd(a,b){return a?.scene===b?.scene&&a?.spot===b?.spot}function sameConnection(c,a,b){return (sameEnd(c.a,a)&&sameEnd(c.b,b))||(sameEnd(c.a,b)&&sameEnd(c.b,a))} ${funcs}`,ctx);
const S='TAVERN';const e=id=>({scene:S,spot:id});
const scenes={TAVERN:{spots:[{id:'SPOT_01',type:'transfer'},{id:'SPOT_02',type:'tofrom'},{id:'SPOT_03',type:'tofrom'},{id:'SPOT_04',type:'transfer'},{id:'SPOT_05',type:'waypoint'}]},ROOM:{spots:[{id:'SPOT_01',type:'transfer'},{id:'SPOT_02',type:'tofrom'}]}};
const c=(a,b)=>({a,b});const first=c(e('SPOT_01'),e('SPOT_02'));
const valid=(edge,existing=[])=>ctx.validConnection(edge,existing,scenes);
assert.equal(valid(first),true,'one transfer-marker link allowed');
assert.equal(valid(c(e('SPOT_03'),e('SPOT_01')),[first]),false,'one marker per transfer');
assert.equal(valid(c(e('SPOT_02'),e('SPOT_04')),[first]),false,'one transfer per marker');
assert.equal(valid(c(e('SPOT_02'),e('SPOT_03'))),false,'no marker-to-marker links');
assert.equal(valid(c(e('SPOT_02'),e('SPOT_05'))),false,'no marker-to-waypoint links');
assert.equal(valid(c(e('SPOT_02'),{scene:'ROOM',spot:'SPOT_01'})),false,'marker stays in scene');
assert.equal(valid(c(e('SPOT_01'),{scene:'ROOM',spot:'SPOT_01'})),true,'existing cross-scene navigation preserved');
assert.equal(valid(c(e('SPOT_01'),e('SPOT_05'))),true,'ordinary navigation preserved');
assert.equal(valid(c(e('SPOT_01'),e('MISSING'))),false,'no dangling links');
const sanitized=ctx.cleanConnections([first,first,c(e('SPOT_03'),e('SPOT_01')),c(e('SPOT_01'),e('SPOT_05'))],scenes);
assert.equal(sanitized.length,2,'sanitize duplicates and conflicting markers');
assert.equal(ctx.isPresentationConnection(first,scenes),true);
assert.equal(ctx.isPresentationConnection(c(e('SPOT_01'),e('SPOT_05')),scenes),false);
console.log('Lab To/From validation: 12 assertions passed');
